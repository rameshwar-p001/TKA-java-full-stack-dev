//// Bit wise operator 

package Day5;

public class p6 {
    public static void main(String[] args) {
         
        System.out.println(7 & 6);  // And
        System.out.println(56 | 12);    // or
        System.out.println(98 ^ 12);    //X-Or
        System.out.println(~10);        // +ve complement
        System.out.println(~-(10));     // -ve complement
        System.out.println(5<<3);       // Bit wise left shift
        System.out.println(5>>3);       // Bit wise right shift
    }
}




